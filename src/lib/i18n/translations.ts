export function translateTagLabel(tagOrLabel: string, lang: AppLanguage): string {
  if (lang === "en") {
    return TAG_TRANSLATIONS_EN[tagOrLabel] || tagOrLabel;
  }
  return tagOrLabel;
}

export function translateSpeciesName(speciesId: string, fallbackName: string, lang: AppLanguage): string {
  if (lang === "en") {
    return SPECIES_NAMES_EN[speciesId] || fallbackName;
  }
  return fallbackName;
}

